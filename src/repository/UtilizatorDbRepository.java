package repository;

import domain.Utilizator;
import domain.Validator;
import exceptions.RepositoryException;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/** Repository for persisting users in the PostgreSQL database. */
public class UtilizatorDbRepository implements Repository<Long, Utilizator> {
    private final Validator<Utilizator> validator;
    private final String url;
    private final String user;
    private final String password;

    /**
     * Creates a user repository configured for a database connection.
     *
     * @param validator the validator applied to users
     * @param url the database connection URL
     * @param user the database user name
     * @param password the database user's password
     */
    public UtilizatorDbRepository(Validator<Utilizator> validator, String url, String user, String password) {
        this.validator = validator;
        this.url = url;
        this.user = user;
        this.password = password;
    }

    /**
     * Finds a user by database identifier.
     *
     * @param id the user identifier
     * @return the matching user, or {@code null} if not found
     * @throws IllegalArgumentException if {@code id} is {@code null}
     * @throws RepositoryException if the database operation fails
     */
    @Override
    public Utilizator findOne(Long id) {
        requireId(id);
        String sql = "SELECT id, first_name, last_name FROM users WHERE id = ?";
        try (Connection connection = openConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            try (ResultSet result = statement.executeQuery()) {
                return result.next() ? readUser(result) : null;
            }
        } catch (SQLException e) {
            throw new RepositoryException("Could not find user " + id, e);
        }
    }

    /**
     * Returns all users.
     *
     * @return all users
     * @throws RepositoryException if the database operation fails
     */
    @Override
    public Iterable<Utilizator> findAll() {
        String sql = "SELECT id, first_name, last_name FROM users ORDER BY id";
        try (Connection connection = openConnection();
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet result = statement.executeQuery()) {
            List<Utilizator> users = new ArrayList<>();
            while (result.next()) {
                users.add(readUser(result));
            }
            return users;
        } catch (SQLException e) {
            throw new RepositoryException("Could not load users", e);
        }
    }

    /**
     * Saves a user and assigns the ID generated by the database.
     *
     * @param entity the user to save
     * @return the existing user with the same name, or {@code null} if saved
     * @throws IllegalArgumentException if {@code entity} is {@code null}
     * @throws exceptions.ValidationException if the user is invalid
     * @throws RepositoryException if the database operation fails
     */
    @Override
    public Utilizator save(Utilizator entity) {
        if (entity == null) {
            throw new IllegalArgumentException("The entity cannot be null!");
        }
        validator.validate(entity);

        String findSql = "SELECT id, first_name, last_name FROM users WHERE first_name = ? AND last_name = ?";
        String insertSql = "INSERT INTO users (first_name, last_name) VALUES (?, ?)";
        try (Connection connection = openConnection();
             PreparedStatement find = connection.prepareStatement(findSql)) {
            find.setString(1, entity.getPrenume());
            find.setString(2, entity.getNume());
            try (ResultSet result = find.executeQuery()) {
                if (result.next()) {
                    return readUser(result);
                }
            }
            try (PreparedStatement insert = connection.prepareStatement(insertSql, Statement.RETURN_GENERATED_KEYS)) {
                insert.setString(1, entity.getPrenume());
                insert.setString(2, entity.getNume());
                if (insert.executeUpdate() != 1) {
                    throw new SQLException("Inserting a user did not affect exactly one row.");
                }
                try (ResultSet generatedKeys = insert.getGeneratedKeys()) {
                    if (!generatedKeys.next()) {
                        throw new SQLException("The database did not return the generated user ID.");
                    }
                    entity.setId(generatedKeys.getLong(1));
                }
            }
            return null;
        } catch (SQLException e) {
            throw new RepositoryException("Could not save user", e);
        }
    }

    /**
     * Deletes a user by database identifier.
     *
     * @param id the user identifier
     * @return the deleted user, or {@code null} if not found
     * @throws IllegalArgumentException if {@code id} is {@code null}
     * @throws RepositoryException if the database operation fails
     */
    @Override
    public Utilizator delete(Long id) {
        requireId(id);
        Utilizator deleted = findOne(id);
        if (deleted == null) {
            return null;
        }
        String sql = "DELETE FROM users WHERE id = ?";
        try (Connection connection = openConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id);
            return statement.executeUpdate() == 1 ? deleted : null;
        } catch (SQLException e) {
            throw new RepositoryException("Could not delete user " + id, e);
        }
    }

    /**
     * Updates an existing user without changing its database identifier.
     *
     * @param entity the user containing the updated data
     * @return {@code null} if updated; otherwise the supplied user
     * @throws IllegalArgumentException if {@code entity} or its ID is {@code null}
     * @throws exceptions.ValidationException if the user is invalid
     * @throws RepositoryException if the database operation fails
     */
    @Override
    public Utilizator update(Utilizator entity) {
        if (entity == null || entity.getId() == null) {
            throw new IllegalArgumentException("The entity and its ID cannot be null!");
        }
        validator.validate(entity);
        String sql = "UPDATE users SET first_name = ?, last_name = ? WHERE id = ?";
        try (Connection connection = openConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, entity.getPrenume());
            statement.setString(2, entity.getNume());
            statement.setLong(3, entity.getId());
            return statement.executeUpdate() == 1 ? null : entity;
        } catch (SQLException e) {
            throw new RepositoryException("Could not update user " + entity.getId(), e);
        }
    }

    private Utilizator readUser(ResultSet result) throws SQLException {
        Utilizator userEntity = new Utilizator(result.getString("last_name"), result.getString("first_name"));
        userEntity.setId(result.getLong("id"));
        return userEntity;
    }

    private Connection openConnection() throws SQLException {
        return DriverManager.getConnection(url, user, password);
    }

    private void requireId(Long id) {
        if (id == null) {
            throw new IllegalArgumentException("The ID cannot be null!");
        }
    }

}
